#!/bin/zsh
# Sourced build helpers. No private-key, trust, TCC, or launch operations.
paneru_fail() { print -u2 -- "Signing: $*"; return 1; }
paneru_load_signing() {
    paneru_config="${PANERU_SIGNING_CONFIG:-$HOME/Library/Application Support/local.paneru.preferences/development-signing.plist}"
    paneru_identity="${PANERU_SIGNING_IDENTITY:-}"
    paneru_mode="${PANERU_SIGNING_REQUIREMENT_MODE:-}"
    paneru_keychain="${PANERU_SIGNING_KEYCHAIN:-}"
    if [[ -e "$paneru_config" ]]; then
        [[ -f "$paneru_config" && ! -L "$paneru_config" ]] || { paneru_fail 'Config must be a regular file, not a symlink.'; return 1; }
        plutil -lint "$paneru_config" >/dev/null || { paneru_fail 'Invalid signing config.'; return 1; }
        [[ -n "$paneru_identity" ]] || paneru_identity=$(/usr/libexec/PlistBuddy -c 'Print :Identity' "$paneru_config") || return 1
        [[ -n "$paneru_mode" ]] || paneru_mode=$(/usr/libexec/PlistBuddy -c 'Print :RequirementMode' "$paneru_config") || return 1
        [[ -n "$paneru_keychain" ]] || paneru_keychain=$(/usr/libexec/PlistBuddy -c 'Print :Keychain' "$paneru_config") || return 1
    fi
    paneru_mode="${paneru_mode:-default}"
}
paneru_validate_signing() {
    [[ "$paneru_mode" == default || "$paneru_mode" == certificate ]] || { paneru_fail 'Requirement mode must be default or certificate.'; return 1; }
    [[ "$paneru_identity" == [0-9A-Fa-f]## && ${#paneru_identity} -eq 40 ]] || {
        paneru_fail 'Select the full 40-hex certificate fingerprint. Configure signing first, or explicitly use --ad-hoc for disposable builds.'; return 1;
    }
    paneru_identity="${paneru_identity:u}"
    if [[ -n "$paneru_keychain" && ! -f "$paneru_keychain" ]]; then paneru_fail 'Selected keychain file does not exist.'; return 1; fi
}
paneru_identity_available() {
    local paneru_listing
    local -a paneru_keychains=()
    [[ -z "$paneru_keychain" ]] || paneru_keychains+=("$paneru_keychain")
    # Include matching identities, not only system-trusted ones: a local
    # certificate-bound DR does not require installing a trusted root.
    paneru_listing=$(security find-identity -p codesigning "${paneru_keychains[@]}") || {
        paneru_fail 'Could not inspect available signing identities. Unlock/select the keychain yourself if necessary.'; return 1;
    }
    print -r -- "$paneru_listing" | awk '{print toupper($2)}' | rg -q -x "$paneru_identity" || {
        paneru_fail 'Selected certificate/private-key identity is unavailable. No ad-hoc fallback was used.'; return 1;
    }
}
paneru_bundle_id() {
    local paneru_bundle_id
    paneru_bundle_id=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$1/Contents/Info.plist") || return 1
    [[ "$paneru_bundle_id" == [A-Za-z0-9.-]## ]] || { paneru_fail 'Unexpected bundle identifier.'; return 1; }
    print -r -- "$paneru_bundle_id"
}
paneru_leaf_hash() {
    local paneru_cert_dir paneru_hash
    paneru_cert_dir=$(mktemp -d "${TMPDIR:-/tmp}/Paneru-certificate.XXXXXX") || return 1
    # This optional long-option argument must use '='. A separate token is
    # interpreted by the native CLI as another code path, not as the prefix.
    if ! codesign --display --extract-certificates="$paneru_cert_dir/cert-" "$1" >/dev/null 2>&1 || [[ ! -f "$paneru_cert_dir/cert-0" ]]; then
        rm -rf "$paneru_cert_dir"; return 1
    fi
    paneru_hash=$(shasum -a 1 "$paneru_cert_dir/cert-0" | awk '{print toupper($1)}')
    rm -rf "$paneru_cert_dir"
    [[ ${#paneru_hash} -eq 40 ]] || return 1
    print -r -- "$paneru_hash"
}
paneru_requirement() {
    local paneru_text
    paneru_text=$(codesign --display -r- "$1" 2>/dev/null) || return 1
    print -r -- "$paneru_text" | sed -n 's/^designated => //p'
}
paneru_stable_requirement() {
    # Accept the signer terms generated by codesign or our exact leaf pin.
    # Reject identifier-only and version-specific ad-hoc requirements.
    [[ -n "$1" && "$1" != *cdhash* && ( "$1" == *'anchor '* || "$1" == *'certificate '* ) ]]
}
paneru_sign_bundle() {
    local paneru_app="$1" paneru_identifier paneru_actual paneru_requirement_text
    paneru_identifier=$(paneru_bundle_id "$paneru_app") || return 1
    local -a paneru_arguments=(--force --sign "$paneru_identity")
    [[ -z "$paneru_keychain" ]] || paneru_arguments+=(--keychain "$paneru_keychain")
    if [[ "$paneru_mode" == certificate ]]; then
        paneru_requirement_text="identifier \"$paneru_identifier\" and certificate leaf = H\"$paneru_identity\""
        paneru_arguments+=(--requirements "=designated => $paneru_requirement_text")
    fi
    codesign "${paneru_arguments[@]}" "$paneru_app" || return 1
    codesign --verify --strict --all-architectures "$paneru_app" || return 1
    paneru_actual=$(paneru_leaf_hash "$paneru_app") || { paneru_fail 'Signed bundle has no certificate chain.'; return 1; }
    [[ "$paneru_actual" == "$paneru_identity" ]] || { paneru_fail 'Actual signing certificate differs from the selected fingerprint.'; return 1; }
    paneru_requirement_text=$(paneru_requirement "$paneru_app") || return 1
    paneru_stable_requirement "$paneru_requirement_text" || {
        paneru_fail 'A stable certificate-bound designated requirement was not produced.'; return 1;
    }
    codesign --verify --strict --all-architectures -R "=$paneru_requirement_text" "$paneru_app" || return 1
    print -r -- "Signed with certificate $paneru_actual ($paneru_mode requirement)."
}
