#!/bin/zsh
# Sourced build helpers. No private-key, trust, TCC, or launch operations.
rd_fail() { print -u2 -- "Signing: $*"; return 1; }
rd_load_signing() {
    rd_config="${RIBBONDESK_SIGNING_CONFIG:-$HOME/Library/Application Support/local.prototype.RibbonDesk/development-signing.plist}"
    rd_identity="${RIBBONDESK_SIGNING_IDENTITY:-}"
    rd_mode="${RIBBONDESK_SIGNING_REQUIREMENT_MODE:-}"
    rd_keychain="${RIBBONDESK_SIGNING_KEYCHAIN:-}"
    if [[ -e "$rd_config" ]]; then
        [[ -f "$rd_config" && ! -L "$rd_config" ]] || { rd_fail 'Config must be a regular file, not a symlink.'; return 1; }
        plutil -lint "$rd_config" >/dev/null || { rd_fail 'Invalid signing config.'; return 1; }
        [[ -n "$rd_identity" ]] || rd_identity=$(/usr/libexec/PlistBuddy -c 'Print :Identity' "$rd_config") || return 1
        [[ -n "$rd_mode" ]] || rd_mode=$(/usr/libexec/PlistBuddy -c 'Print :RequirementMode' "$rd_config") || return 1
        [[ -n "$rd_keychain" ]] || rd_keychain=$(/usr/libexec/PlistBuddy -c 'Print :Keychain' "$rd_config") || return 1
    fi
    rd_mode="${rd_mode:-default}"
}
rd_validate_signing() {
    [[ "$rd_mode" == default || "$rd_mode" == certificate ]] || { rd_fail 'Requirement mode must be default or certificate.'; return 1; }
    [[ "$rd_identity" == [0-9A-Fa-f]## && ${#rd_identity} -eq 40 ]] || {
        rd_fail 'Select the full 40-hex certificate fingerprint. Configure signing first, or explicitly use --ad-hoc for disposable builds.'; return 1;
    }
    rd_identity="${rd_identity:u}"
    if [[ -n "$rd_keychain" && ! -f "$rd_keychain" ]]; then rd_fail 'Selected keychain file does not exist.'; return 1; fi
}
rd_identity_available() {
    local rd_listing
    local -a rd_keychains=()
    [[ -z "$rd_keychain" ]] || rd_keychains+=("$rd_keychain")
    # Include matching identities, not only system-trusted ones: a local
    # certificate-bound DR does not require installing a trusted root.
    rd_listing=$(security find-identity -p codesigning "${rd_keychains[@]}") || {
        rd_fail 'Could not inspect available signing identities. Unlock/select the keychain yourself if necessary.'; return 1;
    }
    print -r -- "$rd_listing" | awk '{print toupper($2)}' | rg -q -x "$rd_identity" || {
        rd_fail 'Selected certificate/private-key identity is unavailable. No ad-hoc fallback was used.'; return 1;
    }
}
rd_bundle_id() {
    local rd_bundle_id
    rd_bundle_id=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$1/Contents/Info.plist") || return 1
    [[ "$rd_bundle_id" == [A-Za-z0-9.-]## ]] || { rd_fail 'Unexpected bundle identifier.'; return 1; }
    print -r -- "$rd_bundle_id"
}
rd_leaf_hash() {
    local rd_cert_dir rd_hash
    rd_cert_dir=$(mktemp -d "${TMPDIR:-/tmp}/RibbonDesk-certificate.XXXXXX") || return 1
    # This optional long-option argument must use '='. A separate token is
    # interpreted by the native CLI as another code path, not as the prefix.
    if ! codesign --display --extract-certificates="$rd_cert_dir/cert-" "$1" >/dev/null 2>&1 || [[ ! -f "$rd_cert_dir/cert-0" ]]; then
        rm -rf "$rd_cert_dir"; return 1
    fi
    rd_hash=$(shasum -a 1 "$rd_cert_dir/cert-0" | awk '{print toupper($1)}')
    rm -rf "$rd_cert_dir"
    [[ ${#rd_hash} -eq 40 ]] || return 1
    print -r -- "$rd_hash"
}
rd_requirement() {
    local rd_text
    rd_text=$(codesign --display -r- "$1" 2>/dev/null) || return 1
    print -r -- "$rd_text" | sed -n 's/^designated => //p'
}
rd_stable_requirement() {
    # Accept the signer terms generated by codesign or our exact leaf pin.
    # Reject identifier-only and version-specific ad-hoc requirements.
    [[ -n "$1" && "$1" != *cdhash* && ( "$1" == *'anchor '* || "$1" == *'certificate '* ) ]]
}
rd_sign_bundle() {
    local rd_app="$1" rd_identifier rd_actual rd_requirement_text
    rd_identifier=$(rd_bundle_id "$rd_app") || return 1
    local -a rd_arguments=(--force --sign "$rd_identity")
    [[ -z "$rd_keychain" ]] || rd_arguments+=(--keychain "$rd_keychain")
    if [[ "$rd_mode" == certificate ]]; then
        rd_requirement_text="identifier \"$rd_identifier\" and certificate leaf = H\"$rd_identity\""
        rd_arguments+=(--requirements "=designated => $rd_requirement_text")
    fi
    codesign "${rd_arguments[@]}" "$rd_app" || return 1
    codesign --verify --strict --all-architectures "$rd_app" || return 1
    rd_actual=$(rd_leaf_hash "$rd_app") || { rd_fail 'Signed bundle has no certificate chain.'; return 1; }
    [[ "$rd_actual" == "$rd_identity" ]] || { rd_fail 'Actual signing certificate differs from the selected fingerprint.'; return 1; }
    rd_requirement_text=$(rd_requirement "$rd_app") || return 1
    rd_stable_requirement "$rd_requirement_text" || {
        rd_fail 'A stable certificate-bound designated requirement was not produced.'; return 1;
    }
    codesign --verify --strict --all-architectures -R "=$rd_requirement_text" "$rd_app" || return 1
    print -r -- "Signed with certificate $rd_actual ($rd_mode requirement)."
}
